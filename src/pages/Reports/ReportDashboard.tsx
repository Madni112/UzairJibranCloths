            const effectiveOB = cOpenBal > 0 ? cOpenBal : Math.abs(Number(obVch?.total_amount || obVch?.debit || obVch?.credit || 0));
            const obDate = obVch?.voucher_date || cust.opening_balance_date || '2026-06-22';
